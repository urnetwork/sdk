func generateVectors() (*Vectors, error) {
	vectors := &Vectors{
		Comment: "Generated by gen_lag.go from the Go sdk and connect (lag.dev/PLAN.md S1); DO NOT EDIT. Bytes are hex, except fields named *Base64 (standard base64), uploadKey (unpadded base64url, as the M4 hello carries it) and the ticket text (M0).",
	}
	rng := rand.New(rand.NewPCG(0x1a9dec, 0x5eed))

	ipInputs := ipVectorInputs(rng)
	for _, input := range ipInputs {
		vector := CanonicalIpVector{Input: input}
		if addr, err := netip.ParseAddr(input); err == nil {
			canonical := addr.Unmap().String()
			vector.Canonical = &canonical
		}
		vectors.CanonicalIps = append(vectors.CanonicalIps, vector)
	}

	names, err := measurementNameVectors(ipInputs)
	if err != nil {
		return nil, err
	}
	vectors.MeasurementNames = names
	vectors.MeasurementHosts = measurementHostVectors(names)

	extenderColors, hueColors, err := extenderColorVectors(ipInputs)
	if err != nil {
		return nil, err
	}
	vectors.ExtenderColors = extenderColors
	vectors.HueColors = hueColors

	keystream, err := keystreamVectors()
	if err != nil {
		return nil, err
	}
	vectors.Keystream = keystream

	if err := signedVectors(vectors); err != nil {
		return nil, err
	}
	return vectors, nil
}

