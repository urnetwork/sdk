func main() {
	check := flag.Bool("check", false, "compare against committed output without writing it")
	flag.Parse()
	outputs, err := generate()
	if err == nil {
		paths := []string{countryColorsTsPath, countryColorsJsonPath, vectorsPath}
		for _, path := range paths {
			output := outputs[path]
			if *check {
				current, readErr := os.ReadFile(path)
				if readErr != nil || !bytes.Equal(current, output) {
					err = fmt.Errorf("%s is stale; run `make generate_lag` and commit the result", path)
					break
				}
			} else if err = os.MkdirAll(filepath.Dir(path), 0755); err == nil {
				err = os.WriteFile(path, output, 0644)
			}
			if err != nil {
				break
			}
		}
	}
	if err != nil {
		fmt.Fprintf(os.Stderr, "Error generating lag tables and vectors: %v\n", err)
		os.Exit(1)
	}
	if *check {
		fmt.Println("Generated lag tables and vectors are up to date")
	} else {
		fmt.Println("Generated lag tables and vectors successfully")
	}
}

func generate() (map[string][]byte, error) {
	codes := strings.Fields(countryCodes)
	if len(codes) != 250 {
		return nil, fmt.Errorf("expected 250 country codes, have %d", len(codes))
	}
	slices.Sort(codes)
	if len(slices.Compact(slices.Clone(codes))) != len(codes) {
		return nil, fmt.Errorf("duplicate country code")
	}
	colors := map[string]string{}
	for _, code := range codes {
		colors[code] = sdk.GetColorHex(code)
	}

	var ts strings.Builder
	ts.WriteString("// Code generated by gen_lag.go; DO NOT EDIT.\n")
	ts.WriteString("//\n")
	ts.WriteString("// Every ISO 3166-1 alpha-2 code, and XK, in lower case, mapped to the color\n")
	ts.WriteString("// sdk GetColorHex gives it (lag.dev/PLAN.md S1). The same table is\n")
	ts.WriteString("// country_colors.generated.json, for readers outside TypeScript.\n")
	ts.WriteString("// Regenerate with `make generate_lag` when the palette changes.\n\n")
	ts.WriteString("export const COUNTRY_COLOR_HEXES: Readonly<Record<string, string>> = {\n")
	for _, code := range codes {
		fmt.Fprintf(&ts, "  %q: %q,\n", code, colors[code])
	}
	ts.WriteString("};\n")

	colorsJson, err := encodeJson(colors)
	if err != nil {
		return nil, err
	}
	vectors, err := generateVectors()
	if err != nil {
		return nil, err
	}
	vectorsJson, err := encodeJson(vectors)
	if err != nil {
		return nil, err
	}
	return map[string][]byte{
		countryColorsTsPath:   []byte(ts.String()),
		countryColorsJsonPath: colorsJson,
		vectorsPath:           vectorsJson,
	}, nil
}

func encodeJson(value any) ([]byte, error) {
	var out bytes.Buffer
	encoder := json.NewEncoder(&out)
	encoder.SetEscapeHTML(false)
	encoder.SetIndent("", "  ")
	if err := encoder.Encode(value); err != nil {
		return nil, err
	}
	return out.Bytes(), nil
}

// A fixed key or seed, derived from a label so the vectors never change.
func fixedBytes(label string, n int) []byte {
	sum := sha256.Sum256([]byte("lag.dev vectors: " + label))
	return sum[:n]
}

