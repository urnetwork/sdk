/**
 * Generate the lag.dev browser SDK's tables and test vectors from Go
 * (lag.dev/PLAN.md S1).
 *
 * The TypeScript in src/lag mirrors Go -- the sdk's colors, connect's
 * measurement names, tickets and record encoding, the M6 keystream -- and
 * these outputs are what pin it there:
 *
 *   src/lag/country_colors.generated.ts    the country palette, for the SDK
 *   src/lag/country_colors.generated.json  the same table, for the web/web
 *                                          link-preview renderer (W3)
 *   test/lag/vectors.json                  vectors the SDK tests replay
 *
 * Every input is fixed, so the output is too: `-check` compares it with the
 * committed files without writing them.
 */

