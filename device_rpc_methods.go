// device_rpc_methods.go -- what the device rpc serves.
//
// A method is listed here to be served. Listing it is also what keeps it in a
// binding: the linker prunes the methods that nothing can reach, and the server
// doesn't find them with reflect (device_rpc_server.go says why). A new rpc method
// that isn't listed answers "rpc: can't find method", which a caller of an optional
// method takes for an older peer, so
// TestDeviceRpcMethodTablesServeEveryMethod holds each table to the methods of its
// type, by the rules net/rpc uses to find them.

